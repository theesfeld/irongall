fn done(ctx: &ApplyCtx<'_>, d: &str) -> TargetStatus {
    if ctx.dry_run {
        TargetStatus::DryRun {
            summary: d.into(),
        }
    } else {
        TargetStatus::Ok {
            detail: Some(d.into()),
        }
    }
}
