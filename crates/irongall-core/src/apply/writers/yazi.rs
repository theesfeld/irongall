use crate::apply::{ApplyCtx, TargetStatus};
use crate::error::Result;
use crate::markers::CommentStyle;

pub fn apply(ctx: &mut ApplyCtx<'_>) -> Result<TargetStatus> {
    let dir = ctx.paths.config_home.join("yazi");
    let flavor_dir = dir.join("flavors/irongall.yazi");
    ctx.write_file(&flavor_dir.join("flavor.toml"), &flavor(ctx))?;

    let theme = dir.join("theme.toml");
    let body = "[flavor]\ndark = \"irongall\"\nlight = \"irongall\"";
    ctx.patch_file(&theme, body, CommentStyle::Hash, true)?;
    Ok(done(ctx, "flavor irongall"))
}

